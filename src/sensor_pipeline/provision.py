"""Broker security material: a local certificate authority, the broker's TLS certificate,
one random password per station and for the ingestor, and the access-control list.

Everything is generated, nothing is committed. Running it again keeps what exists (the CA,
the passwords already handed to devices) and only adds what is missing.

Files written to `out`:
    ca.crt, ca.key            local CA; ca.crt goes on every client (stations, ingestor)
    server.crt, server.key    the broker's certificate, signed by the CA
    credentials.json          {username: password}; read by the simulator and the ingestor
    passwords                 username:password lines, hashed by mosquitto_passwd -U at start
    acl                       who may publish or subscribe where
"""

from __future__ import annotations

import ipaddress
import json
import os
import secrets
from collections.abc import Iterable, Sequence
from datetime import UTC, datetime, timedelta
from pathlib import Path

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.x509.oid import ExtendedKeyUsageOID, NameOID

from sensor_pipeline.messages import TOPIC_ROOT

INGESTOR_USER = "ingestor"
BROKER_HOSTNAMES = ("broker", "localhost")

# Each station may only write its own telemetry and status (%u is the username, which is
# the station id): a stolen or misconfigured device cannot impersonate another one. The
# ingestor may only read.
ACL = f"""\
# Generated by `sensor-pipeline provision-broker`.
pattern write {TOPIC_ROOT}/%u/telemetry
pattern write {TOPIC_ROOT}/%u/status

user {INGESTOR_USER}
topic read {TOPIC_ROOT}/+/telemetry
topic read {TOPIC_ROOT}/+/status
"""


def _write_private(path: Path, data: bytes) -> None:
    """Create a file readable by its owner only."""
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "wb") as f:
        f.write(data)
    path.chmod(0o600)


def _pem_key(key: ec.EllipticCurvePrivateKey) -> bytes:
    return key.private_bytes(
        serialization.Encoding.PEM,
        serialization.PrivateFormat.PKCS8,
        serialization.NoEncryption(),
    )


def _name(common_name: str) -> x509.Name:
    return x509.Name(
        [
            x509.NameAttribute(NameOID.ORGANIZATION_NAME, "Caribbean Sensor Pipeline"),
            x509.NameAttribute(NameOID.COMMON_NAME, common_name),
        ]
    )


def _certificate_authority(now: datetime) -> tuple[ec.EllipticCurvePrivateKey, x509.Certificate]:
    # P-256: supported by mbedTLS on the ESP32 and much cheaper there than RSA.
    key = ec.generate_private_key(ec.SECP256R1())
    name = _name("Antilles sensors local CA")
    cert = (
        x509.CertificateBuilder()
        .subject_name(name)
        .issuer_name(name)
        .public_key(key.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(now - timedelta(minutes=5))
        .not_valid_after(now + timedelta(days=3650))
        .add_extension(x509.BasicConstraints(ca=True, path_length=0), critical=True)
        .add_extension(
            x509.KeyUsage(
                digital_signature=False,
                content_commitment=False,
                key_encipherment=False,
                data_encipherment=False,
                key_agreement=False,
                key_cert_sign=True,
                crl_sign=True,
                encipher_only=False,
                decipher_only=False,
            ),
            critical=True,
        )
        .sign(key, hashes.SHA256())
    )
    return key, cert


def _server_certificate(
    ca_key: ec.EllipticCurvePrivateKey,
    ca_cert: x509.Certificate,
    hostnames: Iterable[str],
    now: datetime,
) -> tuple[ec.EllipticCurvePrivateKey, x509.Certificate]:
    key = ec.generate_private_key(ec.SECP256R1())
    names: list[x509.GeneralName] = []
    for host in [*hostnames, "127.0.0.1"]:
        try:
            names.append(x509.IPAddress(ipaddress.ip_address(host)))
        except ValueError:
            names.append(x509.DNSName(host))
    cert = (
        x509.CertificateBuilder()
        .subject_name(_name("mqtt-broker"))
        .issuer_name(ca_cert.subject)
        .public_key(key.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(now - timedelta(minutes=5))
        .not_valid_after(now + timedelta(days=825))
        .add_extension(x509.SubjectAlternativeName(names), critical=False)
        .add_extension(x509.ExtendedKeyUsage([ExtendedKeyUsageOID.SERVER_AUTH]), critical=False)
        .add_extension(x509.BasicConstraints(ca=False, path_length=None), critical=True)
        .sign(ca_key, hashes.SHA256())
    )
    return key, cert


def provision_broker(
    out: Path,
    station_ids: Sequence[str],
    hostnames: Sequence[str] = BROKER_HOSTNAMES,
) -> list[str]:
    """Generate the missing security files in `out`. Returns the names of the files written."""
    out.mkdir(parents=True, exist_ok=True)
    now = datetime.now(UTC)
    written: list[str] = []

    if not (out / "ca.crt").exists():
        ca_key, ca_cert = _certificate_authority(now)
        _write_private(out / "ca.key", _pem_key(ca_key))
        (out / "ca.crt").write_bytes(ca_cert.public_bytes(serialization.Encoding.PEM))
        server_key, server_cert = _server_certificate(ca_key, ca_cert, hostnames, now)
        _write_private(out / "server.key", _pem_key(server_key))
        (out / "server.crt").write_bytes(server_cert.public_bytes(serialization.Encoding.PEM))
        written += ["ca.crt", "ca.key", "server.crt", "server.key"]

    credentials_path = out / "credentials.json"
    credentials: dict[str, str] = (
        json.loads(credentials_path.read_text(encoding="utf-8"))
        if credentials_path.exists()
        else {}
    )
    added = False
    for user in [INGESTOR_USER, *station_ids]:
        if user not in credentials:
            credentials[user] = secrets.token_urlsafe(24)
            added = True
    if added or not credentials_path.exists():
        _write_private(credentials_path, json.dumps(credentials, indent=2).encode())
        _write_private(
            out / "passwords",
            "".join(f"{user}:{password}\n" for user, password in credentials.items()).encode(),
        )
        written += ["credentials.json", "passwords"]

    (out / "acl").write_text(ACL, encoding="utf-8")
    written.append("acl")
    return written


def load_credentials(path: Path) -> dict[str, str]:
    credentials: dict[str, str] = json.loads(path.read_text(encoding="utf-8"))
    return credentials
